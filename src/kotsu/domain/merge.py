"""Merging data between devices (D39). Pure: takes and returns states.

A *state* is the whole content of a database, as a dictionary (the same format as the
exchange file): `accounts`, `categories`, `recurrences`, `entries` and `tombstones`. Records
refer to each other by `uid`, never by the local `id`.

Rules (the same in the Android app; the cases in `vectors/` apply to both):

- Each record has `changed_at`, a `milliseconds-counter-replica` stamp that compares as
  text. For the same `uid`, the larger stamp wins, with the whole record.
- A deleted entry leaves a tombstone. It beats the entry if it is newer than it.
- Accounts and categories with the same name (case-insensitive) become one: the smallest
  `uid` stays, with the newest content.
- Series: the newest template wins; `generated_until` is always the larger of the two.

Merging is commutative and idempotent: A+B gives the same as B+A, and merging the same file
twice changes nothing.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import re
from collections.abc import Iterable
from dataclasses import dataclass, field

from kotsu.domain import currency

FORMAT = 2
ZERO_STAMP = "0000000000000-0000-00000000"
SECTIONS = ("accounts", "categories", "recurrences", "entries", "tombstones")

_STAMP = re.compile(r"\d{13}-\d{4}-[0-9a-f]{8}")
_KINDS = ("income", "expense")


class ExchangeError(ValueError):
    """An exchange file that cannot be used. The message is shown to the user as is."""


# --- stamps and identity -----------------------------------------------------


def stamp(now_ms: int, last: str, replica: str) -> str:
    """Next stamp: never smaller than or equal to `last`, even with the clock behind."""
    ms, counter = int(last[:13]), int(last[14:18])
    if now_ms > ms:
        ms, counter = now_ms, 0
    elif counter < 9999:
        counter += 1
    else:
        ms, counter = ms + 1, 0
    return f"{ms:013d}-{counter:04d}-{replica}"


def month_uid(group: str, year: int, month: int) -> str:
    """`uid` of the month generated by a series: the same on any device."""
    return f"{group}-{year:04d}-{month:02d}"


def name_key(name: str) -> str:
    """How two account or category names are compared (Itaú = ITAÚ)."""
    return name.strip().casefold()


# --- canonical form and check code -------------------------------------------


def _text(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "1" if value else "0"
    return str(value).replace("\\", "\\\\").replace("\n", "\\n").replace("\x1f", "\\u")


def _line(prefix: str, fields: Iterable[object]) -> str:
    return "\x1f".join([prefix, *(_text(f) for f in fields)])


def _account_line(a: dict) -> str:
    return _line("A", (a["uid"], a["name"], a["color"]))


def _category_line(c: dict) -> str:
    return _line("C", (c["uid"], c["name"], c["recurring"]))


def _recurrence_line(r: dict) -> str:
    fields = ("group", "day", "description", "amount", "kind", "account", "category", "ended")
    return _line("R", (r[f] for f in fields))


def _entry_line(entry: dict) -> str:
    i = entry["installment"] or {}
    return _line(
        "E",
        (
            entry["uid"],
            entry["date"],
            entry["description"],
            entry["amount"],
            entry["kind"],
            entry["account"],
            entry["category"],
            i.get("group"),
            i.get("number"),
            i.get("total"),
            entry["recurrence"],
        ),
    )


def canonical_form(state: dict) -> str:
    """Text that sums up the content, identical on any device with the same data.

    One line per record, fields separated by U+001F, each section in `uid` order.
    Stamps, `generated_until` and months generated by a series and never touched
    (`generated`) are left out: each device generates future months up to where the person
    has browsed.
    """
    lines = sorted(_account_line(a) for a in state["accounts"])
    lines += sorted(_category_line(c) for c in state["categories"])
    lines += sorted(_recurrence_line(r) for r in state["recurrences"])
    lines += sorted(_entry_line(x) for x in state["entries"] if not x["generated"])
    lines += sorted(_line("T", (x["uid"],)) for x in state["tombstones"])
    return "\n".join(lines)


def check_code(state: dict) -> str:
    """Check code: 12 hex digits of the SHA-256 of the canonical form."""
    h = hashlib.sha256(canonical_form(state).encode("utf-8")).hexdigest()
    return f"{h[0:4]}-{h[4:8]}-{h[8:12]}"


# --- format 1 (Portuguese keys) -----------------------------------------------

_V1_SECTIONS = {
    "contas": "accounts",
    "categorias": "categories",
    "recorrencias": "recurrences",
    "lancamentos": "entries",
    "lapides": "tombstones",
}
_V1_FIELDS = {
    "nome": "name",
    "cor": "color",
    "recorrente": "recurring",
    "alterado_em": "changed_at",
    "grupo": "group",
    "dia": "day",
    "descricao": "description",
    "valor": "amount",
    "tipo": "kind",
    "conta": "account",
    "categoria": "category",
    "gerada_ate": "generated_until",
    "encerrada": "ended",
    "data": "date",
    "recorrencia": "recurrence",
    "gerado": "generated",
    "parcela": "installment",
    "numero": "number",
    "excluido_em": "deleted_at",
}
_V1_KINDS = {"receita": "income", "despesa": "expense"}


def _upgrade_record(record: object) -> object:
    if not isinstance(record, dict):
        return record
    new = {}
    for key, value in record.items():
        key = _V1_FIELDS.get(key, key)
        if key == "installment":
            value = _upgrade_record(value)
        elif key == "kind":
            value = _V1_KINDS.get(value, value)
        new[key] = value
    return new


def upgrade_v1(state: dict) -> dict:
    """Translates a format-1 file (written by versions with Portuguese names) to format 2."""
    new = {k: v for k, v in state.items() if k not in _V1_SECTIONS}
    for old, section in _V1_SECTIONS.items():
        records = state.get(old)
        new[section] = (
            [_upgrade_record(r) for r in records] if isinstance(records, list) else records
        )
    new["format"] = FORMAT
    return new


# --- validation --------------------------------------------------------------


def validate(state: object) -> dict:
    """Checks a state read from a file. Raises `ExchangeError`; returns the state.

    A format-1 file is translated to the current format first.
    """
    if not isinstance(state, dict) or state.get("app") != "kotsu":
        raise ExchangeError("this file is not a Kotsu export")
    fmt = state.get("format", state.get("formato"))
    if not isinstance(fmt, int) or isinstance(fmt, bool) or fmt < 1:
        raise ExchangeError("this file is not a Kotsu export")
    if fmt > FORMAT:
        raise ExchangeError(
            f"file in format {fmt}, newer than this Kotsu (format {FORMAT}):"
            " update Kotsu on this device"
        )
    if fmt == 1:
        state = upgrade_v1(state)
    try:
        _validate_content(state)
    except (KeyError, TypeError, AttributeError) as error:
        raise ExchangeError(f"exchange file incomplete or damaged ({error})") from None
    return state


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise ExchangeError(f"invalid exchange file: {message}")


def _integer(value: object) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _non_blank(value: object) -> bool:
    return isinstance(value, str) and bool(value.strip())


def _date(value: object) -> bool:
    try:
        return isinstance(value, str) and dt.date.fromisoformat(value).isoformat() == value
    except ValueError:
        return False


def _valid_stamp(value: object) -> bool:
    return isinstance(value, str) and _STAMP.fullmatch(value) is not None


def _validate_content(state: dict) -> None:
    for section in SECTIONS:
        _require(isinstance(state[section], list), f"missing the list of {section}")

    for section, label in (("accounts", "account"), ("categories", "category")):
        uids, names = set(), set()
        for item in state[section]:
            _require(_non_blank(item["uid"]), f"{label} without uid")
            _require(_non_blank(item["name"]), f"{label} without name")
            _require(_valid_stamp(item["changed_at"]), f"stamp of {label} {item['name']}")
            _require(item["uid"] not in uids, f"duplicate {label} ({item['name']})")
            _require(name_key(item["name"]) not in names, f"duplicate {label} ({item['name']})")
            uids.add(item["uid"])
            names.add(name_key(item["name"]))
    for account in state["accounts"]:
        _require(isinstance(account["color"], str), f"color of account {account['name']}")
    for category in state["categories"]:
        _require(isinstance(category["recurring"], bool), f"category {category['name']}")
    accounts = {a["uid"] for a in state["accounts"]}
    categories = {c["uid"] for c in state["categories"]}

    def movement(item: dict, what: str) -> None:
        _require(isinstance(item["description"], str), f"description of {what}")
        _require(_integer(item["amount"]) and item["amount"] > 0, f"amount of {what}")
        _require(item["kind"] in _KINDS, f"kind of {what}")
        _require(item["account"] in accounts, f"unknown account in {what}")
        _require(
            item["category"] is None or item["category"] in categories,
            f"unknown category in {what}",
        )
        _require(_valid_stamp(item["changed_at"]), f"stamp of {what}")

    series = set()
    for serie in state["recurrences"]:
        _require(_non_blank(serie["group"]), "series without group")
        what = f"series {serie['group']}"
        _require(serie["group"] not in series, f"duplicate {what}")
        series.add(serie["group"])
        _require(_integer(serie["day"]) and 1 <= serie["day"] <= 31, f"day of {what}")
        _require(_date(serie["generated_until"]), f"generated_until of {what}")
        _require(isinstance(serie["ended"], bool), f"ended of {what}")
        movement(serie, what)

    uids = set()
    for entry in state["entries"]:
        _require(_non_blank(entry["uid"]), "entry without uid")
        what = f"entry {entry['uid']}"
        _require(entry["uid"] not in uids, f"duplicate {what}")
        uids.add(entry["uid"])
        _require(_date(entry["date"]), f"date of {what}")
        _require(isinstance(entry["generated"], bool), f"generated of {what}")
        _require(
            entry["recurrence"] is None or entry["recurrence"] in series,
            f"unknown series in {what}",
        )
        installment = entry["installment"]
        if installment is not None:
            _require(_non_blank(installment["group"]), f"installment of {what}")
            _require(
                _integer(installment["number"])
                and _integer(installment["total"])
                and 1 <= installment["number"] <= installment["total"],
                f"installment of {what}",
            )
        movement(entry, what)

    tombstones = set()
    for tombstone in state["tombstones"]:
        _require(_non_blank(tombstone["uid"]), "deletion without uid")
        _require(tombstone["uid"] not in tombstones, f"duplicate deletion ({tombstone['uid']})")
        tombstones.add(tombstone["uid"])
        _require(_valid_stamp(tombstone["deleted_at"]), f"stamp of deletion {tombstone['uid']}")


# --- merging -----------------------------------------------------------------


def _newest(a: dict | None, b: dict, line) -> dict:
    """The record with the larger stamp; on a tie (should not happen), the larger canonical
    line."""
    if a is None:
        return b
    return max(a, b, key=lambda x: (x["changed_at"], line(x)))


def _join_by_name(a: list[dict], b: list[dict], line) -> tuple[list[dict], dict[str, str]]:
    """Joins accounts (or categories) from both sides. Returns the list and `old uid -> new`."""
    by_uid: dict[str, dict] = {}
    for item in (*a, *b):
        by_uid[item["uid"]] = _newest(by_uid.get(item["uid"]), item, line)
    groups: dict[str, list[dict]] = {}
    for uid in sorted(by_uid):
        groups.setdefault(name_key(by_uid[uid]["name"]), []).append(by_uid[uid])
    joined, mapping = [], {}
    for group in groups.values():  # in uid order: the first is the smallest
        content = max(group, key=lambda x: x["changed_at"])  # tie: the smallest uid
        joined.append({**content, "uid": group[0]["uid"]})
        for item in group:
            mapping[item["uid"]] = group[0]["uid"]
    return sorted(joined, key=lambda x: x["uid"]), mapping


def merge(a: dict, b: dict) -> dict:
    """Joins two valid states into one (data sections only, each in uid order)."""
    accounts, account_map = _join_by_name(a["accounts"], b["accounts"], _account_line)
    categories, category_map = _join_by_name(a["categories"], b["categories"], _category_line)

    def repoint(item: dict) -> dict:
        category = item["category"]
        return {
            **item,
            "account": account_map[item["account"]],
            "category": None if category is None else category_map[category],
        }

    series: dict[str, dict] = {}
    for serie in (*a["recurrences"], *b["recurrences"]):
        serie = repoint(serie)
        other = series.get(serie["group"])
        winner = _newest(other, serie, _recurrence_line)
        generated = (
            serie["generated_until"]
            if other is None
            else max(other["generated_until"], serie["generated_until"])
        )
        series[serie["group"]] = {**winner, "generated_until": generated}

    tombstones: dict[str, str] = {}
    for tombstone in (*a["tombstones"], *b["tombstones"]):
        uid = tombstone["uid"]
        tombstones[uid] = max(tombstones.get(uid, ""), tombstone["deleted_at"])

    entries: dict[str, dict] = {}
    for entry in (*a["entries"], *b["entries"]):
        entry = repoint(entry)
        entries[entry["uid"]] = _newest(
            entries.get(entry["uid"]),
            entry,
            lambda x: _entry_line(x) + _text(x["generated"]),
        )
    alive = [x for x in entries.values() if tombstones.get(x["uid"], "") < x["changed_at"]]

    return {
        "accounts": accounts,
        "categories": categories,
        "recurrences": sorted(series.values(), key=lambda x: x["group"]),
        "entries": sorted(alive, key=lambda x: x["uid"]),
        "tombstones": [{"uid": uid, "deleted_at": tombstones[uid]} for uid in sorted(tombstones)],
    }


def highest_stamp(state: dict) -> str:
    """The largest stamp in the state (so the local clock moves past it)."""
    stamps = [ZERO_STAMP]
    for section in ("accounts", "categories", "recurrences", "entries"):
        stamps += [x["changed_at"] for x in state[section]]
    stamps += [x["deleted_at"] for x in state["tombstones"]]
    return max(stamps)


# --- comparison (for verifying) -----------------------------------------------


@dataclass(frozen=True, slots=True)
class Summary:
    """What the merge changed on this device, in entries."""

    added: int = 0
    changed: int = 0
    removed: int = 0

    @property
    def nothing(self) -> bool:
        return not (self.added or self.changed or self.removed)


def summarize(before: dict, after: dict) -> Summary:
    """Compares the entries before and after merging."""
    old = {x["uid"]: _visible(x, before) for x in before["entries"]}
    new = {x["uid"]: _visible(x, after) for x in after["entries"]}
    return Summary(
        added=len(new.keys() - old.keys()),
        changed=sum(1 for uid in new.keys() & old.keys() if new[uid] != old[uid]),
        removed=len(old.keys() - new.keys()),
    )


def _names(state: dict, section: str) -> dict[str, str]:
    return {x["uid"]: x["name"] for x in state[section]}


def _visible(entry: dict, state: dict, names: tuple[dict, dict] | None = None) -> tuple:
    """What the person sees of the entry, with names instead of uids."""
    accounts, categories = names or (_names(state, "accounts"), _names(state, "categories"))
    i = entry["installment"] or {}
    return (
        entry["date"],
        entry["description"],
        entry["amount"],
        entry["kind"],
        name_key(accounts[entry["account"]]),
        name_key(categories[entry["category"]]) if entry["category"] else None,
        i.get("number"),
        i.get("total"),
    )


@dataclass(frozen=True, slots=True)
class Comparison:
    """Differences between the data here and that of a file from another device."""

    code_here: str
    code_there: str
    only_here: list[dict] = field(default_factory=list)
    only_there: list[dict] = field(default_factory=list)
    different: list[tuple[dict, dict]] = field(default_factory=list)  # (here, there)

    @property
    def equal(self) -> bool:
        return self.code_here == self.code_there


def compare(here: dict, there: dict) -> Comparison:
    """Lists the entries that exist on only one side or that differ.

    A month generated by a series and never touched does not count as a difference, unless
    the other side deleted it.
    """
    names_here = (_names(here, "accounts"), _names(here, "categories"))
    names_there = (_names(there, "accounts"), _names(there, "categories"))
    from_here = {x["uid"]: x for x in here["entries"]}
    from_there = {x["uid"]: x for x in there["entries"]}
    tombstones_here = {x["uid"] for x in here["tombstones"]}
    tombstones_there = {x["uid"] for x in there["tombstones"]}
    only_here, only_there, different = [], [], []
    for uid in sorted(from_here.keys() | from_there.keys()):
        mine, theirs = from_here.get(uid), from_there.get(uid)
        if mine and theirs:
            if (not mine["generated"] or not theirs["generated"]) and _visible(
                mine, here, names_here
            ) != _visible(theirs, there, names_there):
                different.append((mine, theirs))
        elif mine and (not mine["generated"] or uid in tombstones_there):
            only_here.append(mine)
        elif theirs and (not theirs["generated"] or uid in tombstones_here):
            only_there.append(theirs)
    return Comparison(check_code(here), check_code(there), only_here, only_there, different)


def describe(entry: dict, state: dict) -> str:
    """One line to show the entry in a list of differences."""
    accounts, categories = _names(state, "accounts"), _names(state, "categories")
    day = dt.date.fromisoformat(entry["date"]).strftime("%d/%m/%Y")
    sign = "+" if entry["kind"] == "income" else "-"
    parts = [day, f"{sign}{currency.format_cents(entry['amount'])}"]
    if entry["description"]:
        parts.append(entry["description"])
    if entry["installment"]:
        parts.append(f"{entry['installment']['number']}/{entry['installment']['total']}")
    if entry["category"]:
        parts.append(f"#{categories[entry['category']]}")
    parts.append(f"@{accounts[entry['account']]}")
    return " ".join(parts)
