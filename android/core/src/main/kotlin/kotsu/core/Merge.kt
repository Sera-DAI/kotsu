package kotsu.core

import java.security.MessageDigest
import java.util.Locale

/**
 * Merging data between devices (D39). Pure: takes and returns states.
 * Mirrors kotsu.domain.merge; checked by vectors/merge.json and vectors/stamp.json.
 *
 * - For the same `uid`, the larger `changed_at` stamp wins, with the whole record.
 * - A tombstone beats the entry if it is newer than it.
 * - A deleted account's tombstone (D44), newer than the account, removes it and its older
 *   entries and series; anything newer keeps the account.
 * - Accounts and categories with the same name (case-insensitive) become one: the smallest
 *   `uid` stays, with the newest content.
 * - Series: the newest template wins; `generatedUntil` is the larger of the two.
 */
object Merge {
    const val FORMAT = 2
    const val ZERO_STAMP = "0000000000000-0000-00000000"

    /** Next stamp: never smaller than or equal to `last`, even with the clock behind. */
    fun stamp(nowMs: Long, last: String, replica: String): String {
        var ms = last.substring(0, 13).toLong()
        var counter = last.substring(14, 18).toInt()
        if (nowMs > ms) {
            ms = nowMs; counter = 0
        } else if (counter < 9999) {
            counter += 1
        } else {
            ms += 1; counter = 0
        }
        return "%013d-%04d-%s".format(ms, counter, replica)
    }

    /** `uid` of the month generated by a series: the same on any device. */
    fun monthUid(group: String, year: Int, month: Int) = "%s-%04d-%02d".format(group, year, month)

    /** How two account or category names are compared (Itaú = ITAÚ). */
    fun nameKey(name: String): String = name.trim().lowercase(Locale.ROOT).replace("ß", "ss")

    // --- canonical form and check code ------------------------------------------------

    private fun text(value: Any?): String = when (value) {
        null -> ""
        is Boolean -> if (value) "1" else "0"
        else -> value.toString().replace("\\", "\\\\").replace("\n", "\\n").replace("\u001f", "\\u")
    }

    private fun line(prefix: String, vararg fields: Any?) =
        (listOf(prefix) + fields.map(::text)).joinToString("\u001f")

    internal fun accountLine(a: Account) = line("A", a.uid, a.name, a.color)
    internal fun categoryLine(c: Category) = line("C", c.uid, c.name, c.recurring)
    internal fun seriesLine(r: Series) =
        line("R", r.group, r.day, r.description, r.amount, r.kind.text, r.account, r.category, r.ended)

    internal fun entryLine(e: Entry) = line(
        "E", e.uid, e.date.toString(), e.description, e.amount, e.kind.text, e.account, e.category,
        e.installment?.group, e.installment?.number, e.installment?.total, e.recurrence,
    )

    /** Text that sums up the content; stamps and untouched generated months are left out. */
    fun canonicalForm(s: State): String {
        val lines = s.accounts.map(::accountLine).sorted() +
            s.categories.map(::categoryLine).sorted() +
            s.recurrences.map(::seriesLine).sorted() +
            s.entries.filter { !it.generated }.map(::entryLine).sorted() +
            s.tombstones.map { line("T", it.uid) }.sorted()
        return lines.joinToString("\n")
    }

    /** Check code: 12 hex digits of the SHA-256 of the canonical form (`a3f9-12bc-77de`). */
    fun checkCode(s: State): String {
        val h = MessageDigest.getInstance("SHA-256").digest(canonicalForm(s).toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it) }
        return "${h.substring(0, 4)}-${h.substring(4, 8)}-${h.substring(8, 12)}"
    }

    // --- merging ----------------------------------------------------------------------

    /** The record with the larger stamp; on a tie, the larger canonical line (first wins if equal). */
    private fun <T> newest(a: T?, b: T, stampOf: (T) -> String, lineOf: (T) -> String): T {
        if (a == null) return b
        val c = stampOf(a).compareTo(stampOf(b)).takeIf { it != 0 } ?: lineOf(a).compareTo(lineOf(b))
        return if (c >= 0) a else b
    }

    private fun <T> joinByName(
        items: List<T>, uid: (T) -> String, name: (T) -> String, at: (T) -> String,
        lineOf: (T) -> String, withUid: (T, String) -> T,
    ): Pair<List<T>, Map<String, String>> {
        val byUid = LinkedHashMap<String, T>()
        for (item in items) byUid[uid(item)] = newest(byUid[uid(item)], item, at, lineOf)
        val groups = LinkedHashMap<String, MutableList<T>>()
        for (u in byUid.keys.sorted()) groups.getOrPut(nameKey(name(byUid[u]!!))) { mutableListOf() }.add(byUid[u]!!)
        val joined = mutableListOf<T>()
        val mapping = HashMap<String, String>()
        for (group in groups.values) {
            val first = uid(group[0])
            var content = group[0]
            for (x in group) if (at(x) > at(content)) content = x
            joined.add(withUid(content, first))
            for (x in group) mapping[uid(x)] = first
        }
        return joined.sortedBy(uid) to mapping
    }

    /** Joins two valid states into one (each section in uid order). */
    fun merge(a: State, b: State): State {
        val (accounts, accountMap) = joinByName(
            a.accounts + b.accounts, { it.uid }, { it.name }, { it.changedAt }, ::accountLine,
        ) { x, u -> x.copy(uid = u) }
        val (categories, categoryMap) = joinByName(
            a.categories + b.categories, { it.uid }, { it.name }, { it.changedAt }, ::categoryLine,
        ) { x, u -> x.copy(uid = u) }

        val tombstones = HashMap<String, String>()
        for (t in a.tombstones + b.tombstones) tombstones[t.uid] = maxOf(tombstones[t.uid] ?: "", t.deletedAt)

        // A deleted account (D44): its tombstone, if newer than the account, takes along every
        // entry and series of it that is older than the tombstone.
        val gone = HashMap<String, String>()
        for ((old, new) in accountMap) tombstones[old]?.let { gone[new] = maxOf(gone[new] ?: "", it) }
        val accountGone = accounts.filter { (gone[it.uid] ?: "") > it.changedAt }.associate { it.uid to gone.getValue(it.uid) }
        fun survives(account: String, changedAt: String) = (accountGone[account] ?: "") < changedAt

        val series = LinkedHashMap<String, Series>()
        for (raw in a.recurrences + b.recurrences) {
            val s = raw.copy(account = accountMap.getValue(raw.account), category = raw.category?.let(categoryMap::getValue))
            val other = series[s.group]
            val winner = newest(other, s, { it.changedAt }, ::seriesLine)
            val until = if (other == null) s.generatedUntil else maxOf(other.generatedUntil, s.generatedUntil)
            series[s.group] = winner.copy(generatedUntil = until)
        }

        val entries = LinkedHashMap<String, Entry>()
        for (raw in a.entries + b.entries) {
            val e = raw.copy(account = accountMap.getValue(raw.account), category = raw.category?.let(categoryMap::getValue))
            entries[e.uid] = newest(entries[e.uid], e, { it.changedAt }) { entryLine(it) + text(it.generated) }
        }
        val alive = entries.values.filter { (tombstones[it.uid] ?: "") < it.changedAt && survives(it.account, it.changedAt) }
        val keptSeries = series.values.filter { survives(it.account, it.changedAt) }
        val used = (alive.map { it.account } + keptSeries.map { it.account }).toSet()

        return State(
            accounts = accounts.filter { it.uid !in accountGone || it.uid in used },
            categories = categories,
            recurrences = keptSeries.sortedBy { it.group },
            entries = alive.sortedBy { it.uid },
            tombstones = tombstones.keys.sorted().map { Tombstone(it, tombstones.getValue(it)) },
        )
    }

    /** The largest stamp in the state (so the local clock moves past it). */
    fun highestStamp(s: State): String = (
        listOf(ZERO_STAMP) + s.accounts.map { it.changedAt } + s.categories.map { it.changedAt } +
            s.recurrences.map { it.changedAt } + s.entries.map { it.changedAt } + s.tombstones.map { it.deletedAt }
        ).max()

    // --- what changed -----------------------------------------------------------------

    data class Summary(val added: Int = 0, val changed: Int = 0, val removed: Int = 0) {
        val nothing get() = added == 0 && changed == 0 && removed == 0
    }

    private fun visible(e: Entry, s: State): List<Any?> {
        val accounts = s.accounts.associate { it.uid to it.name }
        val categories = s.categories.associate { it.uid to it.name }
        return listOf(
            e.date, e.description, e.amount, e.kind, nameKey(accounts.getValue(e.account)),
            e.category?.let { nameKey(categories.getValue(it)) }, e.installment?.number, e.installment?.total,
        )
    }

    /** Compares the entries before and after merging. */
    fun summarize(before: State, after: State): Summary {
        val old = before.entries.associate { it.uid to visible(it, before) }
        val new = after.entries.associate { it.uid to visible(it, after) }
        return Summary(
            added = (new.keys - old.keys).size,
            changed = new.keys.intersect(old.keys).count { new[it] != old[it] },
            removed = (old.keys - new.keys).size,
        )
    }
}
